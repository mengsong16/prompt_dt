def npify(data):
    for k in data:
        if k == 'terminals':
            dtype = np.bool_
        else:
            dtype = np.float32

        data[k] = np.array(data[k], dtype=dtype)

def generate_one_task(env, maze, env_name, task_idx, max_episode_steps,
                      input_traj_per_subtask, prompt_traj_per_subtask, noisy):
    # add appendix to env name
    if noisy:
        env_name += "-noisy"

    # generate input trajectories for current subtask
    print(f"================= d4rl-{env_name}-{task_idx}-expert ==================")
    #print(f"Goal: {env._target}")

    input_trajectories = []

    for traj_ind in range(input_traj_per_subtask): 
        # new episode
        cur_traj = { 'observations': [], 'actions': [], 'rewards': [], 'terminals': []}
        # set task
        env.set_target(target_location=full_targets[task_idx])
        assert np.array_equal(env._target, full_targets[task_idx]), "Goal location is not set correctly"

        # create expert policy
        # need to recreate every episode!!
        controller = waypoint_controller.WaypointController(maze)

        # reset to a random location
        state = env.reset()
        cur_traj['observations'].append(state)
        returns = 0
        
        for step in range(max_episode_steps+1):
            # get expert action
            position = state[0:2]
            velocity = state[2:4]
            # use done generated by the controller, not by th environment
            act, done = controller.get_action(position, velocity, env._target)
            if step >= max_episode_steps:
                done = True

            if noisy:
                act = act + np.random.randn(*act.shape)*0.5

            act = np.clip(act, -1.0, 1.0)
            
            # step
            state, reward, _, info = env.step(act)
            returns += reward
            
            env.render()

            # append data
            cur_traj['observations'].append(state)
            cur_traj['actions'].append(act)
            cur_traj['rewards'].append(reward)
            cur_traj['terminals'].append(done) # won't be used
            
            if done:
                break

        # throw away s_T
        cur_traj['observations'] = cur_traj['observations'][:-1]

        assert len(cur_traj['observations']) == len(cur_traj['actions']) == len(cur_traj['rewards']) == len(cur_traj['terminals']), "All values should have the same length"

        # convert from list to numpy array for each value
        for key in cur_traj.keys():
            cur_traj[key] = np.array(cur_traj[key])
        
        # check undone trajectories
        if cur_traj['terminals'][-1] == False:
            print(f"Warning: {env_name}-{task_idx}-{traj_ind}: Undone trajectory!")
            print("Trajectory length: ", cur_traj['actions'].shape[0])
            print("Done: ", cur_traj['terminals'][-1])
            #print("Success: ", cur_traj['success'][-1])
        else:
            print(f"Episode terminates at step {cur_traj['terminals'].shape[0]}, return is {returns}")
        
        # add to the pool
        input_trajectories.append(cur_traj)

    exit()
    # sample prompt trajectories
    prompt_trajectories = random.sample(input_trajectories, prompt_traj_per_subtask)
    
    # set up save folder
    folder_name = f'd4rl-{env_name}'
    folder_path = os.path.join(data_path, folder_name)
    if not os.path.exists(folder_path):
        os.makedirs(folder_path)

    # save input trajectories 
    input_traj_file_name = f'd4rl-{env_name}-{task_idx}-expert.pkl'
    input_traj_file_path = os.path.join(folder_path, input_traj_file_name)
    with open(input_traj_file_path, 'wb') as f:
        pickle.dump(input_trajectories, f)
        print("Total input trajectories: ", len(input_trajectories))
        print("======> Saved input trajectories to ", input_traj_file_path)
    
    # save prompt trajectories
    prompt_traj_file_name = f'd4rl-{env_name}-{task_idx}-prompt-expert.pkl'
    prompt_traj_file_path = os.path.join(folder_path, prompt_traj_file_name)
    with open(prompt_traj_file_path, 'wb') as f:
        pickle.dump(prompt_trajectories, f)
        print("Total prompt trajectories: ", len(prompt_trajectories))
        print("======> Saved input trajectories to ", prompt_traj_file_path)

def generate_d4rl_maze(env_name='maze2d-medium-v1', noisy=False):
    # seed everything except environments
    seed_other(seed=1)

    input_traj_per_subtask = 100
    prompt_traj_per_subtask = 5

    # create env
    env = gym.make(env_name)
    env.seed(1)
    max_episode_steps = env._max_episode_steps
    maze = env.str_maze_spec
    
    # recreate env in order to get and set target
    env = maze_model.MazeEnv(maze)

    # loop over all tasks
    all_task_num = len(full_targets)
    for task_idx in range(all_task_num):
        
        # generate input trajectories and prompt trajectories
        generate_one_task(env, maze, env_name, task_idx, max_episode_steps, input_traj_per_subtask, prompt_traj_per_subtask, noisy)
        
    print("Done!")

